def safe_filename(value: str) -> str:
    """Create a Windows-safe filename."""
    cleaned = re.sub(r"[^A-Za-z0-9_-]+", "_", value.strip()).strip("_")
    return cleaned or "project"


def markdown_to_docx(markdown_text: str, document_title: str) -> bytes:
    """Convert generated Markdown into an editable Word document."""
    doc = Document()
    section = doc.sections[0]
    section.top_margin = Inches(0.7)
    section.bottom_margin = Inches(0.7)
    section.left_margin = Inches(0.75)
    section.right_margin = Inches(0.75)

    # Consistent document typography.
    normal = doc.styles["Normal"]
    normal.font.name = "Aptos"
    normal.font.size = Pt(9)

    for style_name, size, hex_color in [
        ("Title", 24, "17365D"),
        ("Heading 1", 17, "17365D"),
        ("Heading 2", 13, "1F6E78"),
        ("Heading 3", 11, "1F6E78"),
    ]:
        style = doc.styles[style_name]
        style.font.name = "Aptos Display"
        style.font.size = Pt(size)
        style.font.bold = True
        style.font.color.rgb = RGBColor.from_string(hex_color)

    title = doc.add_paragraph(style="Title")
    title.alignment = WD_ALIGN_PARAGRAPH.CENTER
    title.add_run(document_title)

    subtitle = doc.add_paragraph()
    subtitle.alignment = WD_ALIGN_PARAGRAPH.CENTER
    run = subtitle.add_run("Generated by DevFlow AI")
    run.italic = True
    run.font.color.rgb = RGBColor(100, 116, 139)
    doc.add_paragraph()

    lines = markdown_text.splitlines()
    in_code = False
    code_lines = []

    for line in lines:
        stripped = line.strip()

        if stripped.startswith("```"):
            if not in_code:
                in_code = True
                code_lines = []
            else:
                p = doc.add_paragraph()
                p.paragraph_format.left_indent = Inches(0.18)
                p.paragraph_format.right_indent = Inches(0.12)
                p.paragraph_format.space_after = Pt(6)
                r = p.add_run("\n".join(code_lines))
                r.font.name = "Consolas"
                r.font.size = Pt(7.5)
                in_code = False
            continue

        if in_code:
            code_lines.append(line)
            continue

        if not stripped or stripped == "---":
            continue

        if stripped.startswith("# "):
            doc.add_heading(stripped[2:].strip(), level=1)
        elif stripped.startswith("## "):
            doc.add_heading(stripped[3:].strip(), level=2)
        elif stripped.startswith("### "):
            doc.add_heading(stripped[4:].strip(), level=3)
        elif re.match(r"^\s*[-*]\s+", line):
            p = doc.add_paragraph(style="List Bullet")
            p.add_run(re.sub(r"^\s*[-*]\s+", "", line))
        elif re.match(r"^\s*\d+\.\s+", line):
            p = doc.add_paragraph(style="List Number")
            p.add_run(re.sub(r"^\s*\d+\.\s+", "", line))
        elif stripped.startswith(">"):
            p = doc.add_paragraph()
            r = p.add_run(stripped[1:].strip())
            r.italic = True
        else:
            doc.add_paragraph(line)

    if in_code and code_lines:
        p = doc.add_paragraph()
        r = p.add_run("\n".join(code_lines))
        r.font.name = "Consolas"
        r.font.size = Pt(7.5)

    # Footer with page number field.
    for sec in doc.sections:
        footer = sec.footer.paragraphs[0]
        footer.alignment = WD_ALIGN_PARAGRAPH.CENTER
        footer.add_run("DevFlow AI  |  Project Development Deliverable  |  ")
        field = OxmlElement("w:fldSimple")
        field.set(qn("w:instr"), "PAGE")
        footer._p.append(field)

    buffer = BytesIO()
    doc.save(buffer)
    return buffer.getvalue()


def markdown_to_pdf(markdown_text: str, document_title: str) -> bytes:
    """Convert generated Markdown into a formatted PDF."""
    buffer = BytesIO()
    pdf = SimpleDocTemplate(
        buffer,
        pagesize=A4,
        rightMargin=17 * mm,
        leftMargin=17 * mm,
        topMargin=17 * mm,
        bottomMargin=18 * mm,
        title=document_title,
        author="DevFlow AI",
    )

    styles = getSampleStyleSheet()
    styles.add(ParagraphStyle(
        name="DevFlowCover",
        parent=styles["Title"],
        fontName="Helvetica-Bold",
        fontSize=22,
        leading=27,
        textColor=colors.HexColor("#17365D"),
        alignment=TA_CENTER,
        spaceAfter=10,
    ))
    styles.add(ParagraphStyle(
        name="DevFlowH1",
        parent=styles["Heading1"],
        fontSize=15,
        leading=19,
        textColor=colors.HexColor("#17365D"),
        spaceBefore=12,
        spaceAfter=6,
    ))
    styles.add(ParagraphStyle(
        name="DevFlowH2",
        parent=styles["Heading2"],
        fontSize=12,
        leading=15,
        textColor=colors.HexColor("#1F6E78"),
        spaceBefore=9,
        spaceAfter=5,
    ))
    styles.add(ParagraphStyle(
        name="DevFlowH3",
        parent=styles["Heading3"],
        fontSize=10,
        leading=13,
        textColor=colors.HexColor("#1F6E78"),
        spaceBefore=7,
        spaceAfter=4,
    ))
    styles.add(ParagraphStyle(
        name="DevFlowBody",
        parent=styles["BodyText"],
        fontSize=8.5,
        leading=11,
        spaceAfter=4,
    ))
    styles.add(ParagraphStyle(
        name="DevFlowCode",
        parent=styles["Code"],
        fontName="Courier",
        fontSize=6.5,
        leading=8,
        leftIndent=7,
        rightIndent=7,
        backColor=colors.HexColor("#F1F5F9"),
        borderPadding=5,
        spaceBefore=4,
        spaceAfter=6,
    ))

    story = [
        Spacer(1, 35 * mm),
        Paragraph(escape(document_title), styles["DevFlowCover"]),
        Paragraph(
            "Generated by DevFlow AI — Multi-Agent Project Development Assistant",
            styles["DevFlowBody"],
        ),
        Spacer(1, 20 * mm),
    ]

    lines = markdown_text.splitlines()
    in_code = False
    code_lines = []

    def format_inline(text: str) -> str:
        value = escape(text)
        value = re.sub(r"\*\*(.+?)\*\*", r"<b>\1</b>", value)
        value = re.sub(r"\*(.+?)\*", r"<i>\1</i>", value)
        value = re.sub(r"`(.+?)`", r'<font name="Courier" size="7">\1</font>', value)
        return value

    for line in lines:
        stripped = line.strip()

        if stripped.startswith("```"):
            if not in_code:
                in_code = True
                code_lines = []
            else:
                story.append(Preformatted("\n".join(code_lines), styles["DevFlowCode"]))
                in_code = False
            continue

        if in_code:
            code_lines.append(line)
            continue

        if not stripped or stripped == "---":
            story.append(Spacer(1, 3))
            continue

        if stripped.startswith("# "):
            story.append(Paragraph(format_inline(stripped[2:]), styles["DevFlowH1"]))
        elif stripped.startswith("## "):
            story.append(Paragraph(format_inline(stripped[3:]), styles["DevFlowH2"]))
        elif stripped.startswith("### "):
            story.append(Paragraph(format_inline(stripped[4:]), styles["DevFlowH3"]))
        elif re.match(r"^\s*[-*]\s+", line):
            item = re.sub(r"^\s*[-*]\s+", "", line)
            story.append(Paragraph("&#8226;&nbsp; " + format_inline(item), styles["DevFlowBody"]))
        elif re.match(r"^\s*\d+\.\s+", line):
            item = re.sub(r"^\s*\d+\.\s+", "", line)
            story.append(Paragraph("&#8226;&nbsp; " + format_inline(item), styles["DevFlowBody"]))
        elif stripped.startswith(">"):
            item = format_inline(stripped[1:].strip())
            story.append(Paragraph("<i>" + item + "</i>", styles["DevFlowBody"]))
        else:
            story.append(Paragraph(format_inline(stripped), styles["DevFlowBody"]))

    if in_code and code_lines:
        story.append(Preformatted("\n".join(code_lines), styles["DevFlowCode"]))

    def add_page_number(canvas, doc):
        canvas.saveState()
        canvas.setFont("Helvetica", 7)
        canvas.setFillColor(colors.HexColor("#64748B"))
        canvas.drawString(17 * mm, 9 * mm, "DevFlow AI | Project Development Deliverable")
        canvas.drawRightString(A4[0] - 17 * mm, 9 * mm, f"Page {doc.page}")
        canvas.restoreState()

    pdf.build(story, onFirstPage=add_page_number, onLaterPages=add_page_number)
    return buffer.getvalue()


