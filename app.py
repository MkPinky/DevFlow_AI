# ---------------------------------------------------------------------
# Run the six-agent workflow
# ---------------------------------------------------------------------
if submitted:
    if not title.strip() or not description.strip() or not features.strip():
        st.error(
            "Please complete Project title, Project description and Required features."
        )
    elif not os.getenv("GROQ_API_KEY"):
        st.error(
            "GROQ_API_KEY is missing. Add it to your .env file and restart the app."
        )
    else:
        project = {
            "title": title.strip(),
            "description": description.strip(),
            "features": features.strip(),
            "language": language,
            "database": database,
            "project_type": project_type,
            "complexity": experience,
            "audience": audience.strip() or "Not specified",
            "constraints": constraints.strip() or "None specified",
        }

        with st.status(
            "The six specialist agents are working...",
            expanded=True,
        ) as status:
            try:
                result = run_development_crew(project)
                status.update(
                    label="Development plan generated successfully.",
                    state="complete",
                )
                st.session_state["devflow_result"] = result
                st.session_state["devflow_title"] = title.strip()
            except Exception as exc:
                status.update(label="Generation failed.", state="error")
                st.error(f"Could not complete the workflow: {exc}")
                st.caption(
                    "Check your API key, internet connection and installed package versions."
                )


# ---------------------------------------------------------------------
# Display results and offer MD, PDF and DOCX downloads
# ---------------------------------------------------------------------
if "devflow_result" in st.session_state:
    result = st.session_state["devflow_result"]
    project_title = st.session_state.get("devflow_title", "Project")

    st.divider()
    st.header(f"Generated plan: {project_title}")

    labels = [
        ("Requirements", "requirements"),
        ("Architecture", "architecture"),
        ("Prototype Code", "code"),
        ("Testing Plan", "testing"),
        ("Documentation", "documentation"),
        ("Project Report", "report"),
    ]

    tabs = st.tabs([label for label, _ in labels])
    for tab, (label, key) in zip(tabs, labels):
        with tab:
            content = result.get(key, "")
            if content:
                st.markdown(content)
            else:
                st.warning("No output was returned for this stage.")

    combined = "\n\n".join(
        f"# {label}\n\n{result.get(key, '') or 'No output was returned for this stage.'}"
        for label, key in labels
    )

    safe_name = safe_filename(project_title)
    base_name = f"{safe_name}_development_plan"

    # Save a copy of the Markdown file in the project's outputs folder.
    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
    markdown_path = OUTPUT_DIR / f"{base_name}.md"
    markdown_path.write_text(combined, encoding="utf-8")

    st.divider()
    st.subheader("⬇️ Download Project Deliverables")
    st.caption(
        "Download the complete six-agent output in your preferred document format."
    )

    try:
        pdf_bytes = markdown_to_pdf(combined, project_title)
        docx_bytes = markdown_to_docx(combined, project_title)

        col_md, col_pdf, col_docx = st.columns(3)

        with col_md:
            st.download_button(
                "📄 Download Markdown",
                data=combined.encode("utf-8"),
                file_name=f"{base_name}.md",
                mime="text/markdown",
                use_container_width=True,
                key="download_md",
            )

        with col_pdf:
            st.download_button(
                "📕 Download PDF",
                data=pdf_bytes,
                file_name=f"{base_name}.pdf",
                mime="application/pdf",
                use_container_width=True,
                key="download_pdf",
            )

        with col_docx:
            st.download_button(
                "📝 Download Word",
                data=docx_bytes,
                file_name=f"{base_name}.docx",
                mime="application/vnd.openxmlformats-officedocument.wordprocessingml.document",
                use_container_width=True,
                key="download_docx",
            )

        st.success("All three download formats are ready.")
    except Exception as exc:
        st.error(f"Could not prepare one or more download formats: {exc}")
        st.caption(
            "Install the document libraries using: "
            "python -m pip install reportlab python-docx"
        )

    st.warning(
        "Safety: DevFlow AI does not automatically execute generated code. "
        "Inspect it, test with sample data, and run it only in an isolated "
        "environment after approval."
    )
